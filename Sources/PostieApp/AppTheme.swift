import SwiftUI

enum AppTheme: String, CaseIterable {
    case system, light, dark

    static let preferenceKey = "appTheme"

    var title: String {
        switch self {
        case .system: "System"
        case .light: "Light"
        case .dark: "Dark"
        }
    }

    var colorScheme: ColorScheme? {
        switch self {
        case .system: nil
        case .light: .light
        case .dark: .dark
        }
    }
}
